package fr.florianpal.fmessage.velocity;

import fr.florianpal.fmessage.platform.ProxyLogger;
import org.slf4j.Logger;

/**
 * Bridges {@link ProxyLogger} onto Velocity's SLF4J logger.
 */
public class VelocityLogger implements ProxyLogger {

    private final Logger logger;

    public VelocityLogger(Logger logger) {
        this.logger = logger;
    }

    @Override
    public void info(String message) {
        logger.info(message);
    }

    @Override
    public void warn(String message) {
        logger.warn(message);
    }

    @Override
    public void error(String message) {
        logger.error(message);
    }

    @Override
    public void error(String message, Throwable throwable) {
        logger.error(message, throwable);
    }
}
