package fr.florianpal.fmessage.bungee;

import fr.florianpal.fmessage.platform.ProxyLogger;

import java.util.logging.Level;
import java.util.logging.Logger;

/**
 * Bridges {@link ProxyLogger} onto BungeeCord's {@code java.util.logging} logger.
 */
public class BungeeLogger implements ProxyLogger {

    private final Logger logger;

    public BungeeLogger(Logger logger) {
        this.logger = logger;
    }

    @Override
    public void info(String message) {
        logger.info(message);
    }

    @Override
    public void warn(String message) {
        logger.warning(message);
    }

    @Override
    public void error(String message) {
        logger.severe(message);
    }

    @Override
    public void error(String message, Throwable throwable) {
        logger.log(Level.SEVERE, message, throwable);
    }
}
